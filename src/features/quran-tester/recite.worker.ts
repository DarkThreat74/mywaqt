/// <reference lib="webworker" />
/**
 * Quran Tester inference worker.
 *
 * Loads the zipformer phoneme engine (tilawa) on onnxruntime-web WASM, all
 * assets served from the /qt/ engine cache (installed on demand). Receives
 * mic PCM at the AudioContext's native rate, resamples to 16 kHz mono, and
 * streams tilawa events (verse_match, word_progress, correction, …) back to
 * the page. Everything stays on-device.
 */
import * as ort from "onnxruntime-web/wasm";
import { createRecognitionSession, type RecognitionSession } from "@tilawa/core";
import MUTA_INDEX from "./muta-index.json";

declare const self: DedicatedWorkerGlobalScope;

const ENGINE_CACHE = "quran-tester-engine-v1";
const OUT_RATE = 16000;

// The engine must boot with no service worker at all — Capacitor's WebView
// has none, and a fresh offline start can precede SW control. Everything the
// engine needs sits in its own bucket, so /qt/ fetches (ort's wasmPaths)
// resolve straight from CacheStorage, and the ort .mjs is pre-blob'd so its
// internal `new Worker(import.meta.url)` pthread spawns never touch the
// network either. Page-side spawn still prefers the real URL (blob: spawn
// inherits the document CSP, which is fine — but keep the SW re-stamp path
// where a SW exists).
{
  const qtBlobs = new Map<string, string>();
  const qtBlob = (path: string) => {
    void caches.open(ENGINE_CACHE)
      .then((c) => c.match(new URL(path, self.location.origin)))
      .then(async (hit) => {
        if (hit) qtBlobs.set(path, URL.createObjectURL(await hit.blob()));
      })
      .catch(() => {});
  };
  // Warmed at script eval — resolved long before ort spawns a pthread.
  qtBlob("/qt/ort-wasm-simd-threaded.mjs");

  const shim = self as unknown as {
    fetch: typeof fetch;
    Worker: typeof Worker;
  };
  const realFetch = shim.fetch.bind(self);
  shim.fetch = async (input: RequestInfo | URL, init?: RequestInit) => {
    const raw = typeof input === "string" || input instanceof URL ? String(input) : input.url;
    const u = new URL(raw, self.location.origin);
    if (u.pathname.startsWith("/qt/")) {
      try {
        const hit = await (await caches.open(ENGINE_CACHE)).match(u);
        if (hit) return hit;
      } catch { /* bucket unreadable — fall through to the real fetch */ }
    }
    return realFetch(input, init);
  };

  const RealWorker = shim.Worker;
  shim.Worker = (function (url: string | URL, opts?: WorkerOptions): Worker {
    const path = new URL(String(url), self.location.origin).pathname;
    const blob = path.startsWith("/qt/") ? qtBlobs.get(path) : undefined;
    return new RealWorker(blob ?? url, opts);
  }) as unknown as typeof Worker;
}

let session: RecognitionSession | null = null;
let sourceRate = 48000;
let queue: Promise<void> = Promise.resolve();

// Take epoch — the page bumps this on every `reset` (new take). Every event
// carries it so the page can drop messages drained from a previous take;
// page-side stamping can't distinguish pre/post-reset messages.
let takeId = 0;
function post(m: Record<string, unknown>) {
  postMessage({ ...m, take: takeId });
}

// Liveness heartbeat — a wedged WASM decode produces no events AND no
// onerror (the thread is stuck, not crashed), so the page can't distinguish
// "quiet recitation" from "dead engine" without a beat. 5s cadence lets the
// page detect a stall in ~25s instead of never.
setInterval(() => {
  try { post({ type: "beat" }); } catch {}
}, 5000);

// Audio goes through a dedicated pump, but pump calls are themselves queued —
// a control message (stop/reset/reanchor/expect) can no longer interleave with
// an in-flight feed and decode stale audio into a reset tracker. The pump
// merges pending chunks and drops the oldest past a 1.5s backlog, so latency
// self-corrects; pendingCtl lets a queued control message interrupt the drain.
let feeding = false;
let audioPending: { samples: Float32Array; rate: number }[] = [];
let pendingCtl = 0;
const MAX_BACKLOG_SEC = 1.5;

// ── Mutashabihat divergence watcher ─────────────────────────────────────
// Filled at init from structuralRules.looks. `muta_approach` fires once per
// differing region when the cursor steps INTO it; `muta_diverge` fires when
// a wrong/unsure verdict lands inside one — the page dings immediately
// instead of waiting for the pause-timed structural pass.
let divLooks: Map<string, { m: [number, number]; regions: number[][] }[]> | null = null;
let divCorpus: { wordSurah: Int32Array; wordAyah: Int32Array; wordInAyah: Int32Array } | null = null;
const mutaSeen = new Set<string>();

// Extended pairwise index — generated by scripts/build-muta-index.mjs into
// the SAME schema the engine's structural-index.json uses
// ({pairs: {"s:a": [[ms,ma, tag,i1,i2,j1,j2, ...]]}, ident}). Bundled into
// the worker IIFE so it needs no fetch and works fully offline.
type MutaRow = { m: [number, number]; regions: number[][] };
type MutaMaps = {
  looks?: Map<string, MutaRow[]>;
  both?: Map<string, MutaRow[]>;
  ident?: Set<string>;
};

function mergeMutaIndex(sm: MutaMaps | undefined) {
  if (!sm) return;
  const sig = (key: string, row: MutaRow) =>
    `${key}>${row.m[0]}:${row.m[1]}|${row.regions.flat().join(",")}`;
  const seenByKey = new Map<string, Set<string>>();
  const addRow = (map: Map<string, MutaRow[]> | undefined, key: string, row: MutaRow) => {
    if (!map) return;
    const s = sig(key, row);
    let seen = seenByKey.get(key);
    if (!seen) {
      seen = new Set((map.get(key) ?? []).map((r) => sig(key, r)));
      seenByKey.set(key, seen);
    }
    if (seen.has(s)) return;
    seen.add(s);
    let arr = map.get(key);
    if (!arr) map.set(key, (arr = []));
    arr.push(row);
  };
  const idx = MUTA_INDEX as { pairs: Record<string, number[][]>; ident?: string[] };
  for (const [key, rows] of Object.entries(idx.pairs ?? {})) {
    const [s, a] = key.split(":").map(Number);
    for (const flat of rows) {
      const m: [number, number] = [flat[0], flat[1]];
      const regions: number[][] = [];
      for (let p = 2; p + 5 <= flat.length; p += 5)
        regions.push([flat[p], flat[p + 1], flat[p + 2], flat[p + 3], flat[p + 4]]);
      if (!regions.length) continue;
      const fwd: MutaRow = { m, regions };
      addRow(sm.looks, key, fwd);
      addRow(sm.both, key, fwd);
      // `both` is bidirectional — give the partner a reversed row (tags
      // 1↔2, i↔j) so landing ON the partner sees the divergence too.
      const rev: MutaRow = {
        m: [s, a],
        regions: regions.map(([t, i1, i2, j1, j2]) => [t === 1 ? 2 : t === 2 ? 1 : t, j1, j2, i1, i2]),
      };
      addRow(sm.both, `${m[0]}:${m[1]}`, rev);
    }
  }
  if (sm.ident) for (const k of idx.ident ?? []) sm.ident.add(k);
}

// NOTE: `cursor` and `verdicts` engine events are SWALLOWED by
// ZipformerSession.handle() — they're folded into `word_progress` before
// onEvent ever sees them. The watcher therefore runs on the events that
// actually arrive: `word_progress` (carries surah/ayah/word_index,
// 0-based in-ayah — fires on both cursor moves and verdict batches),
// `relocated`, and `verse_candidate` (the `located` translation). Verdict
// detail is pulled via session.zipformer.verdicts() — a memoized live
// array, cheap to re-scan each progress tick.
type WordVerdict = {
  state?: string;
  wordIndex?: number;
  lookalike?: { surah: number; ayah: number; conf?: number };
};

function pollVerdicts() {
  const zp = session?.zipformer as unknown as { verdicts?: () => WordVerdict[] } | null;
  const vs = zp?.verdicts?.();
  if (!vs?.length || !divCorpus || !divLooks) return;
  for (const v of vs) {
    // Bare `unsure` is routine CTC mush on correct recitation — only a
    // `wrong` verdict or a named look-alike alternate earns a ding.
    if ((v.state !== "wrong" && !v.lookalike) || v.wordIndex == null) continue;
    const look = v.lookalike;
    const s = divCorpus.wordSurah[v.wordIndex];
    const a = divCorpus.wordAyah[v.wordIndex];
    const w = divCorpus.wordInAyah[v.wordIndex];
    if (look) {
      const key = `x:${s}:${a}:${w}:${look.surah}:${look.ayah}`;
      if (!mutaSeen.has(key)) {
        mutaSeen.add(key);
        // Attach the divergent-region bounds for this twin (if we can
        // find the row) so the page can underline the exact words.
        let from: number | undefined, to: number | undefined;
        for (const row of divLooks.get(`${s}:${a}`) ?? []) {
          if (row.m[0] !== look.surah || row.m[1] !== look.ayah) continue;
          const r = row.regions.find((x) => w >= x[1] && w < x[2]);
          if (r) { from = r[1] + 1; to = r[2]; break; }
        }
        post({
          type: "muta_diverge", surah: s, ayah: a, word: w + 1,
          altSurah: look.surah, altAyah: look.ayah, certain: true,
          conf: look.conf ?? 0, from, to,
        });
      }
      continue; // don't double-ding via the position scan below
    }
    flagDiv(s, a, w, "diverge");
  }
}

function watchMuta(ev: { type?: string; surah?: number; ayah?: number; word_index?: number }) {
  if (!divLooks || !divCorpus) return;
  // A successful locate/relocate starts a new epoch — the same region
  // legitimately re-flags if the reciter slips again on the re-read.
  // `located` is swallowed by the session layer and surfaces as
  // `verse_candidate`; `relocated` passes through unchanged.
  if (ev.type === "relocated" || ev.type === "verse_candidate") {
    mutaSeen.clear();
    return;
  }
  if (ev.type === "word_progress" && ev.word_index != null && ev.surah != null && ev.ayah != null) {
    flagDiv(ev.surah, ev.ayah, ev.word_index, "approach");
    pollVerdicts();
  }
}

// Heard chars belonging to one word — same trail/localWordOfPos mapping the
// stop-dump uses, so "what you said" is the real aligned decode, not a guess.
function heardForWord(wordIndex: number): string {
  const z = session?.zipformer as unknown as {
    engine?: {
      tracker?: {
        heard?: { ch: string }[];
        trail?: number[];
        localWordOfPos?: Int32Array;
        firstWord?: number;
      };
    };
  } | null;
  const tr = z?.engine?.tracker;
  if (!tr?.heard || !tr.trail || !tr.localWordOfPos || tr.trail.length !== tr.heard.length) return "";
  const first = tr.firstWord ?? 0;
  let out = "";
  // Corrections are for the current word; scanning an entire take here made
  // each later correction slower as the transcript grew.
  const firstHeard = Math.max(0, tr.heard.length - 4096);
  for (let i = firstHeard; i < tr.heard.length; i++) {
    const c = tr.heard[i];
    const cell = tr.trail![i];
    if (cell <= 0) continue;
    const w = tr.localWordOfPos![Math.min(cell, tr.localWordOfPos!.length) - 1];
    if (first + w === wordIndex) out += c.ch;
  }
  return out;
}

function flagDiv(s: number, a: number, w: number, mode: "approach" | "diverge") {
  const rows = divLooks!.get(`${s}:${a}`);
  if (!rows) return;
  for (const row of rows) {
    const conf = (row as { conf?: number }).conf ?? 0;
    for (const r of row.regions) {
      const i1 = r[1], i2 = r[2]; // [tag, i1, i2, j1, j2]
      // Approach fires a word EARLY — the heads-up has to land before the
      // divergent word is recited, not as it arrives.
      if (i2 <= i1 || w < i1 - (mode === "approach" ? 1 : 0) || w >= i2) continue;
      const key = `${s}:${a}:${i1}:${row.m[0]}:${row.m[1]}:${mode}`;
      if (mutaSeen.has(key)) continue;
      mutaSeen.add(key);
      post({
        type: mode === "approach" ? "muta_approach" : "muta_diverge",
        surah: s, ayah: a, word: w + 1, // 1-based in-ayah for the page
        altSurah: row.m[0], altAyah: row.m[1],
        conf,
        // Region bounds (1-based) — the page underlines exactly the words
        // where this ayah parts ways with the look-alike.
        from: i1 + 1, to: i2,
        // Hard families (near-identical diffs): an unsure verdict there is
        // indistinguishable from mushy audio — flag silently, never ding.
        soft: mode === "diverge" && conf >= 0.7,
      });
    }
  }
}

async function pumpAudio() {
  if (feeding) return;
  feeding = true;
  try {
    while (audioPending.length && session && !pendingCtl) {
      const chunks = audioPending.splice(0);
      // Pending chunks can carry different source rates (ctx swapped
      // mid-warm) — resample each at its own rate, then merge.
      const parts = chunks.map((c) => resample(c.samples, c.rate));
      const outLen = parts.reduce((s, p) => s + p.length, 0);
      const merged = new Float32Array(outLen);
      let off = 0;
      for (const p of parts) { merged.set(p, off); off += p.length; }
      await session.feed(merged);
    }
  } catch (err) {
    void reportErr(err);
  } finally {
    feeding = false;
  }
}

/** Drain every buffered chunk into the engine (used by stop — the tail of
 *  the take must be judged too, never silently dropped). */
async function drainAudio() {
  while (audioPending.length && session) {
    const chunks = audioPending.splice(0);
    const parts = chunks.map((c) => resample(c.samples, c.rate));
    const merged = new Float32Array(parts.reduce((s, p) => s + p.length, 0));
    let off = 0;
    for (const p of parts) { merged.set(p, off); off += p.length; }
    await session.feed(merged);
  }
}

// A dedicated worker's CSP comes from its own script's RESPONSE headers — a
// stale cached response can carry an old policy while the page is fine.
// Refetching our own URL shows what the server NOW sends, and whether the
// worker was born under a stale policy.
async function reportErr(err: unknown) {
  let wCsp = "?";
  try {
    const r = await fetch(self.location.href, { cache: "no-store" });
    const csp = r.headers.get("content-security-policy") ?? "";
    wCsp = csp.includes("unsafe-eval") ? "fresh" : `stale: ${csp.slice(0, 120)}`;
  } catch {
    wCsp = "unreachable";
  }
  post({
    type: "error",
    message: `${err instanceof Error ? err.message : String(err)} [worker-csp: ${wCsp}]`,
  });
}

async function cached(url: string): Promise<Response> {
  const cache = await caches.open(ENGINE_CACHE);
  // Match by absolute URL — inside a blob: worker a bare "/qt/…" path would
  // resolve against the blob base and never match the stored key.
  const hit = await cache.match(new URL(url, self.location.origin));
  if (!hit) throw new Error(`engine asset missing: ${url}`);
  return hit;
}

async function init(sampleRate: number) {
  // Re-init would stack a second 66MB ONNX session on the first — the
  // session persists across recitations; only reset() runs between takes.
  if (session) {
    // Re-init (e.g. after warmQt) must still adopt the live AudioContext's
    // rate — a warm ctx at 48k followed by a recite ctx at 44.1k would
    // otherwise resample wrong and silently wreck detection.
    sourceRate = sampleRate;
    post({ type: "ready" });
    return;
  }
  sourceRate = sampleRate;
  post({ type: "loading_status", message: "Warming up the engine…" });

  const [modelRes, corpusRes] = await Promise.all([
    cached("/qt/model.onnx"),
    cached("/qt/corpus.json"),
  ]);

  // Threaded WASM needs cross-origin isolation. The page opts in via scoped
  // COOP/COEP on /quran-tester — `crossOriginIsolated` is the canonical
  // signal (SAB presence alone can lag the header check on some browsers);
  // absent headers degrade silently to single-thread, never a hard failure.
  ort.env.wasm.numThreads =
    self.crossOriginIsolated === true && typeof SharedArrayBuffer !== "undefined"
      ? Math.min(4, navigator.hardwareConcurrency || 4)
      : 1;
  ort.env.wasm.wasmPaths = "/qt/";

  const model = await modelRes.arrayBuffer();
  const corpus = await corpusRes.json();

  const sess = await createRecognitionSession({
    ort,
    model,
    corpus,
    // Deliver events via the callback — feed()'s return carries the same
    // messages, but callback delivery can't be lost to a stalled promise.
    onEvent: (m: unknown) => {
      try { watchMuta(m as Parameters<typeof watchMuta>[0]); } catch {}
      // Enrich correction events with the heard phonemes for the flagged
      // word — the popup shows "you said X" alongside the expected word.
      // If the flagged word sits inside a divergent region, also name the
      // look-alike twin: the slip is probably the twin's wording, and the
      // page can display "that's the wording of X:Y" in the same popup.
      try {
        const ev = m as {
          type?: string;
          state?: { issue?: { surah?: number; ayah?: number; word?: number; wordIndex?: number } };
        };
        const iss = ev.state?.issue;
        if (ev.type === "correction" && iss && typeof iss.wordIndex === "number") {
          (ev as Record<string, unknown>).heard = heardForWord(iss.wordIndex);
          if (divLooks && typeof iss.surah === "number" && typeof iss.word === "number") {
            for (const row of divLooks.get(`${iss.surah}:${iss.ayah}`) ?? []) {
              const r = row.regions.find((x) => iss.word! >= x[1] && iss.word! < x[2]);
              if (r) {
                (ev as Record<string, unknown>).muta = {
                  altS: row.m[0], altA: row.m[1],
                  from: r[1] + 1, to: r[2], altFrom: r[3] + 1, altTo: r[4],
                  conf: (row as { conf?: number }).conf ?? 0,
                };
                break;
              }
            }
          }
        }
      } catch {}
      post(m as Record<string, unknown>);
    },
    // Slip head: a logistic probe over the model's encoder frames that
    // scores each tracker's word span acoustically — catches wrong-sounding
    // words (kaf-vs-ha level substitutions) without waiting for word-level
    // alignment to settle. Needs the model's optional encoder output;
    // the manifest declares it, and the head silently stays off if a model
    // without it is ever loaded.
    // "high" was the false-positive factory: the slip probe fires with NO
    // neighbour anchors and even on ayah-boundary words, where pausal forms
    // make the acoustics look most unlike the canonical decode.
    slipHead: "strict",
    // Aggressive search cadence (shorter queries, more frequent full-Quran
    // searches) starves single-threaded WASM decode — the audio backlog
    // overflows, transcript corrupts, locate never lands. Only the verdict
    // observation window is tightened vs default.
    config: {
      // 15 (0.6s) judged the cursor word mid-madd — a held vowel produces no
      // new chars, so `settled` fired while still being pronounced and the
      // stretched slice judged wrong. 20 still flags ~0.8s behind voice.
      settleFrames: 20,
      // Tail-dwell before a non-settled verdict commits: 6 heard chars let a
      // single fluttered token paint `wrong` on correct words.
      commitDwell: 10,
      // A real mistake spikes alignment cost — if relocation triggers too
      // eagerly, a wrong WORD reads as "you moved", the tracker abandons
      // the passage on ~1 word of evidence, and the correction observer
      // (gated off while struggling) never flags the slip. Rebalance:
      // holdRate/lostRate raised so observation keeps running through a
      // rough stretch, and the relocate search needs ~4 ayahs of unheard
      // text (120 chars) — a one-word slip can no longer drag the tracker
      // onto a look-alike ayah (the mutashabihat false-jump).
      holdWindow: 22,
      holdRate: 0.7,
      lostRate: 0.55,
      relocateEveryFrames: 30,
      relocateQueryChars: 120,
      // Drop to the free-search hard reset after 2 bad ticks instead of 3 —
      // a wedged tracker recovers ~1.6s sooner and nothing else uses the
      // struggles counter.
      maxStruggles: 2,
      // A wrong word must be decisively worse than staying: demand the remote
      // hit beat local cost by 0.25 (was 0.12 — a moderate stumble could pass).
      relocateRateMargin: 0.25,
      // Silent-slide guard: DP restart edges used to reach ANY word in the
      // surah for a flat 12 — a mispronounced word could teleport the cursor
      // onto a mutashabih and the mistake scored "ok" against the wrong ayah.
      // Restarts now pay 2/word of distance and cap at 10 words; farther moves
      // must go through lost -> relocate (which emits an event the UI shows).
      jumpPerWord: 2,
      maxJumpWords: 10,
    },
    // Structural rules — the second detection layer. `stop`-timing only
    // flags at end of audio; `pause` raises them live as segments close:
    // skipped ayahs (ayahOrder, guarded mode) and look-alike-verse swaps
    // (similarVerse — the mutashabihat case the word rules can't see).
    structural: { ayahOrder: "guarded", similarVerse: true, timing: "pause" },
    debug: true,
  } as Parameters<typeof createRecognitionSession>[0]);
  // Correction mode: word-level suspects (omission / substitution / vowel /
  // repetition / skipped ayah) stream out as `correction` events. The page
  // turns them into yellow suspects; only user-confirmed mistakes persist.
  sess.zipformer?.correction.setMode("correction");
  // Mutashabihat watch — the engine already ships a per-word look-alike
  // index (structural-index.json → structuralRules.looks: "s:a" → rows of
  // {m:[s,a], regions:[[tag,i1,i2,j1,j2]]}, engine word space). The
  // structural pass only flags at pauses; this watcher turns it live:
  // entering a region that DIFFERS from a look-alike raises muta_approach,
  // and a wrong/unsure verdict inside one raises muta_diverge instantly —
  // the exact "wait for the word that differs, then ding" rule.
  const zp = sess.zipformer as unknown as {
    engine?: { corpus?: { wordSurah: Int32Array; wordAyah: Int32Array; wordInAyah: Int32Array } };
    structuralRules?: { looks?: Map<string, { m: [number, number]; regions: number[][] }[]>; both?: Map<string, { m: [number, number]; regions: number[][] }[]>; ident?: Set<string> };
  } | null;
  // `both` is the bidirectional view — but ?? can't fall back on an EMPTY
  // Map, so prefer whichever side actually has entries.
  const sm = zp?.structuralRules;
  // Merge the app's exhaustive pair index (scripts/build-muta-index.mjs:
  // Waqar144 curated pairs + every shared 3-gram fragment + ending-variant
  // tails like غفور رحيم/حليم) into the engine's curated structural index.
  // engine.looks/idents share these Map/Set references, so divergentOk
  // relocation vetoes and the verdicts dual-score see the union too.
  mergeMutaIndex(sm);
  divLooks = (sm?.both?.size ? sm.both : sm?.looks?.size ? sm.looks : null) ?? null;
  divCorpus = zp?.engine?.corpus ?? null;
  // Identical-text ayahs (refrains like Ar-Rahman's) — relocations and
  // flags between them are undecidable, so the page suppresses the
  // similar_verse accusation on landings inside this set.
  if (zp?.structuralRules?.ident?.size)
    post({ type: "muta_ident", ayahs: [...zp.structuralRules.ident] });
  // Tell the page the look-alike machinery is armed (and how much of the
  // index is live) — a silent dead watcher used to look exactly like a
  // working one from the page side.
  post({ type: "muta_ready", pairs: divLooks?.size ?? 0 });
  // Balanced flagging: omissions flag when under half the word was heard,
  // substitutions need a clearly different word, vowel slips need a confident
  // decoder read. Tighter than this (0.15/0.9) made real slips never surface.
  if (sess.zipformer) Object.assign(sess.zipformer.correction.thresholds, {
    // 0.5 meant a word heard half-way (only the onset clipped) could never flag
    // as an omission — 0.75 restores partial-word omission detection.
    omissionMaxHeard: 0.75,
    // 0.45 flagged 1-2 phoneme noise on short words (ال، في، من — a single
    // bad CTC token in a 3-4 phoneme word is distance ~0.5). 0.55 requires a
    // clearly different word again.
    substitutionDistance: 0.55,
    // Neighbour anchors: 0.4 let mushy decodes qualify as "clear" anchors,
    // which fires every gated rule around them. 0.5 is the middle ground.
    clearMargin: 0.5,
    // Decoder confidence the flagged word itself was heard clearly — 0.35
    // passed on mush. 0.45 is near the default 0.5 but still reachable.
    subMargin: 0.45,
    // Vowel evidence must be stronger than a single harakat token flip —
    // the decoder confidently rewrites internal harakat on normal audio.
    vowelMargin: 0.12,
    // 0.6 fired on mushy decodes; 0.75 approaches the default 0.8 while
    // remaining reachable on real recitation.
    vowelWordMargin: 0.75,
    // GOP stays OFF. The engine's own tuning note: "on real clean takes it
    // still raises false flags that the other rules do not" — enabling it at
    // -5 was a primary false-positive source. The acoustic check remains in
    // the word-level distance rules; deep-grade uses GOP offline instead.
    gopFlag: -Infinity,
    // One extra frame of jitter tolerance before a candidate's persistence
    // clock resets — 4-frame persistence is short, so allow more misses.
    persistGrace: 2,
  });
  // Only publish AFTER full setup — a throw above must not leave a half-
  // configured session that early-returns `ready` on the next init.
  session = sess;
  post({ type: "ready" });
}

/** Cheap linear resampler — fine for 16kHz speech ASR. */
function resample(input: Float32Array, from: number): Float32Array {
  if (from === OUT_RATE) return input;
  const ratio = from / OUT_RATE;
  const out = new Float32Array(Math.floor(input.length / ratio));
  for (let i = 0; i < out.length; i++) {
    const src = i * ratio;
    const lo = Math.floor(src);
    const hi = Math.min(lo + 1, input.length - 1);
    out[i] = input[lo] + (input[hi] - input[lo]) * (src - lo);
  }
  return out;
}

self.onmessage = (e: MessageEvent) => {
  const m = e.data;
  // Control messages interrupt the audio drain — count them while they wait
  // so pumpAudio yields instead of starving stop/reset behind a live stream.
  if (m.type !== "audio" && m.type !== "init") pendingCtl++;
  // Serialize work — feed() and init() must never interleave.
  queue = queue.then(async () => {
    try {
      if (m.type === "init") {
        await init(m.sampleRate);
      } else if (m.type === "audio") {
        // Capture the rate at enqueue — the engine's sourceRate can change
        // on re-init while old chunks still wait.
        audioPending.push({ samples: m.samples as Float32Array, rate: sourceRate });
        // Drop the oldest frames past the backlog cap — better to skip a
        // syllable than to trail the reciter by a growing delay. The drop is
        // surfaced (never silent): the heard stream has a hole and every
        // later word's timing shifts early by the dropped duration.
        // Seconds per chunk, not samples vs current sourceRate — queued
        // chunks keep their own rate tag after a mid-warm rate swap.
        let backlog = audioPending.reduce((s, c) => s + c.samples.length / c.rate, 0);
        let dropped = 0;
        while (backlog > MAX_BACKLOG_SEC && audioPending.length > 1) {
          backlog -= audioPending[0].samples.length / audioPending[0].rate;
          dropped += audioPending[0].samples.length;
          audioPending.shift();
        }
        if (dropped) post({ type: "audio-gap", seconds: dropped / sourceRate });
        queue = queue.then(pumpAudio);
      } else if (m.type === "audio-sync" && session) {
        // Offline replay (recite-coach deep grade): every chunk MUST decode —
        // the realtime pump drops backlog, which corrupts the heard stream
        // and breaks frame→ms calibration. Serialized in the queue; slower
        // than realtime is fine, there is no live cursor to keep up with.
        await session.feed(resample(m.samples, sourceRate));
      } else if (m.type === "expect" && session) {
        session.zipformer?.setExpected(m.passage ?? null);
      } else if (m.type === "stop" && session) {
        await drainAudio(); // the tail of the take is judged too — never dropped
        await session.stop(); // events flow through onEvent
        // Deep-grade tap: dump the heard phoneme stream (chars + CTC frame
        // index each) so callers can measure madd/ghunnah durations.
        // `buffer` caps at 1000 chars — long takes lose the head. The
        // tracker's `heard` is uncapped and aligned, so it carries the
        // whole take; buffer is the fallback for never-locked sessions.
        // framesDecoded lets callers convert frames→ms against the actual
        // audio length.
        const z = session.zipformer as unknown as {
          engine?: {
            buffer?: { ch: string; frame: number; margin: number }[];
            tracker?: {
              heard?: { ch: string; frame: number; margin: number }[];
              trail?: number[];
              localWordOfPos?: Int32Array;
              firstWord?: number;
            };
            corpus?: {
              wordSurah?: Int32Array;
              wordAyah?: Int32Array;
              wordInAyah?: Int32Array;
            };
          };
          decoder?: { framesDecoded?: number };
        } | null;
        // Per-word spans via the tracker trail — heard char i maps to
        // expected position trail[i], and localWordOfPos turns a position
        // into a word inside the locked passage. This is what powers the
        // report's word-by-word timing (pitch + madds land on real words).
        const tr = z?.engine?.tracker;
        const corpus = z?.engine?.corpus;
        const words: {
          surah: number; ayah: number; word: number; wordIndex: number;
          chars: { ch: string; frame: number }[];
        }[] = [];
        if (tr?.heard && tr.trail && tr.localWordOfPos && corpus?.wordSurah && tr.trail.length === tr.heard.length) {
          const byWord = new Map<number, { ch: string; frame: number }[]>();
          tr.heard.forEach((c, i) => {
            const cell = tr.trail![i];
            if (cell <= 0) return;
            const w = tr.localWordOfPos![Math.min(cell, tr.localWordOfPos!.length) - 1];
            const arr = byWord.get(w) ?? [];
            arr.push({ ch: c.ch, frame: c.frame });
            byWord.set(w, arr);
          });
          const first = tr.firstWord ?? 0;
          for (const [local, chars] of [...byWord.entries()].sort((a, b) => a[0] - b[0])) {
            const gi = first + local;
            words.push({
              surah: corpus.wordSurah[gi], ayah: corpus.wordAyah![gi], word: corpus.wordInAyah![gi] + 1,
              wordIndex: gi, chars,
            });
          }
        }
        post({
          type: "heard",
          chars: (tr?.heard?.length ? tr.heard : z?.engine?.buffer) ?? [],
          words,
          framesDecoded: z?.decoder?.framesDecoded ?? 0,
        });
        post({ type: "stopped" });
      } else if (m.type === "reset") {
        // Bookkeeping must run even before init: a reset queued ahead of
        // init on a cold/replacement worker would otherwise leave takeId
        // stale and the page would drop every event of the new session.
        audioPending = [];
        if (typeof m.take === "number") takeId = m.take;
        mutaSeen.clear(); // fresh take — divergent regions may ding again
        session?.reset();
      } else if (m.type === "correction-act" && session) {
        session.zipformer?.correction.act(m.action);
      } else if (m.type === "reanchor" && session) {
        // Hold mode: a rejected relocation snaps the tracker back to the
        // pinned ayah — the move is flagged, the cursor stays put. It's a
        // new epoch for the watcher too: a slip on the re-read must ding.
        mutaSeen.clear();
        session.zipformer?.track(m.s as number, m.a as number, (m.w as number) ?? 0);
      } else if (m.type === "mode" && session) {
        session.zipformer?.correction.setMode(m.mode);
      }
    } catch (err) {
      void reportErr(err);
    } finally {
      if (m.type !== "audio" && m.type !== "init") pendingCtl--;
      // A control message may have paused the drain — resume feeding.
      if (audioPending.length) queue = queue.then(pumpAudio);
    }
  });
};
