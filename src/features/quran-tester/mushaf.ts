/**
 * Madani 15-line mushaf — page data + per-page QPC2 glyph fonts, lazy-cached.
 *
 * Source dataset: zonetecde/mushaf-layout (v2 branch, QPC2 edition) — 604
 * pages, each a JSON of typed lines (surah-header / basmala / text) whose
 * words carry `location` ("s:a:w") and `qpcV2` glyph codepoints rendered by
 * that page's own font — the same mechanism quran.com uses.
 *
 * Pages and fonts fetch on first view and cache into the engine bucket, so a
 * page is a one-time ~150KB cost and works offline after.
 */

import { ENGINE_CACHE } from "./engine";

// Vendored in-repo (scripts/fetch-mushaf.mjs) — same-origin static files,
// additionally cached into the engine bucket so pages work offline forever
// once seen.
const PAGE_BASE = "/data/mushaf/QPC2";
const FONT_BASE = "/fonts/qpc2";
const PAGE_COUNT = 604;

export interface MushafWord {
  location: string; // "surah:ayah:word"
  word: string;
  qpcV2?: string;
}
export interface MushafLine {
  line: number;
  type: "surah-header" | "basmala" | "text" | string;
  text?: string;
  surah?: string;
  verseRange?: string;
  words?: MushafWord[];
  centered?: boolean;
  is_centered?: boolean;
}
export interface MushafPage {
  page: number;
  lines: MushafLine[];
}

/** ayah→page index, generated by scripts/gen-ayah-pages.mjs */
export type AyahPages = Record<string, Record<string, number>>;

export interface SurahMetaEntry { s: number; name: string; en?: string; page: number }

export async function loadAyahPages(): Promise<AyahPages> {
  // cachedAsset, not plain fetch — the recite anchor must survive with no
  // service worker at all (native WebView, pre-SW offline).
  const res = await cachedAsset("/qt/ayah-pages.json", "/data/ayah-pages.json");
  return res.json();
}

export async function loadSurahMeta(): Promise<SurahMetaEntry[]> {
  const res = await cachedAsset("/qt/surah-meta.json", "/data/surah-meta.json");
  return res.json();
}

async function cachedAsset(path: string, url: string): Promise<Response> {
  // CacheStorage only exists in secure contexts — fall back to a plain
  // fetch (HTTP dev over LAN, older WebViews) so pages still load.
  if (typeof caches !== "undefined") {
    try {
      const cache = await caches.open(ENGINE_CACHE);
      const hit = await cache.match(path);
      if (hit) return hit;
      const res = await fetch(url);
      if (res.ok) await cache.put(path, res.clone());
      return res;
    } catch {
      // fall through to plain fetch below
    }
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`mushaf asset ${path}: ${res.status}`);
  return res;
}

const pageCache = new Map<number, Promise<MushafPage>>();

export function loadPage(n: number): Promise<MushafPage> {
  const p = Math.min(PAGE_COUNT, Math.max(1, n));
  let pending = pageCache.get(p);
  if (!pending) {
    const key = `/qt/page-${String(p).padStart(3, "0")}.json`;
    pending = cachedAsset(key, `${PAGE_BASE}/page-${String(p).padStart(3, "0")}.json`).then((r) => r.json());
    // Don't pin a rejected promise in the map — a failed fetch must be
    // retryable on the next attempt instead of being "Loading…" forever.
    pending.catch(() => pageCache.delete(p));
    pageCache.set(p, pending);
  }
  return pending;
}

const loadedFonts = new Set<number>();
let bsmlFont: Promise<string> | null = null;

/** The dedicated basmala glyph font — its private codepoints (ﭑﭒﭓ) don't
 * exist in per-page fonts, which is why basmalas rendered as broken letters. */
export function loadBasmalaFont(): Promise<string> {
  bsmlFont ??= (async () => {
    const res = await cachedAsset("/qt/QPC2BSML.ttf", `${FONT_BASE}/QPC2BSML.ttf`);
    const font = new FontFace("QPC2BSML", await res.arrayBuffer());
    await font.load();
    document.fonts.add(font);
    return "QPC2BSML";
  })();
  bsmlFont.catch(() => { bsmlFont = null; });
  return bsmlFont;
}

/** Register the page's glyph font (downloaded once, cached). */
export async function loadPageFont(n: number): Promise<string> {
  const family = `QPC2-p${n}`;
  if (loadedFonts.has(n)) return family;
  const file = `p${String(n).padStart(3, "0")}.woff2`;
  const res = await cachedAsset(`/qt/${file}`, `${FONT_BASE}/${file}`);
  const font = new FontFace(family, await res.arrayBuffer());
  await font.load();
  document.fonts.add(font);
  loadedFonts.add(n);
  return family;
}

/**
 * Idle background warm — streams every mushaf page + glyph font into the
 * engine bucket a page at a time, so the whole Quran becomes offline-ready
 * without a 90MB up-front wall. Resumes where it left off across sessions
 * (localStorage watermark), skips metered connections, and pauses on any
 * network failure — the next call picks the same page back up.
 */
const WARM_KEY = "qt:mushaf-warm";
let warming = false;

const idle = (fn: () => void) =>
  "requestIdleCallback" in window
    ? requestIdleCallback(fn, { timeout: 4000 })
    : setTimeout(fn, 150);

export function warmMushaf(): void {
  if (warming || typeof caches === "undefined") return;
  const conn = (navigator as { connection?: { saveData?: boolean; effectiveType?: string } }).connection;
  if (conn?.saveData || conn?.effectiveType === "slow-2g") return;
  let p = Math.max(1, Math.min(PAGE_COUNT + 1, Number(localStorage.getItem(WARM_KEY)) || 1));
  warming = true;
  // The small shared assets warm with the run — without these an offline
  // first-open has page JSON but broken basmalas and no surah names.
  void cachedAsset(`/qt/QPC2BSML.ttf`, `${FONT_BASE}/QPC2BSML.ttf`).catch(() => {});
  void cachedAsset(`/qt/ayah-pages.json`, `/data/ayah-pages.json`).catch(() => {});
  void cachedAsset(`/qt/surah-meta.json`, `/data/surah-meta.json`).catch(() => {});
  if (p > PAGE_COUNT) { warming = false; return; } // already fully warm

  const tick = () => {
    if (p > PAGE_COUNT) { warming = false; return; }
    const pad = String(p).padStart(3, "0");
    Promise.all([
      cachedAsset(`/qt/page-${pad}.json`, `${PAGE_BASE}/page-${pad}.json`),
      cachedAsset(`/qt/p${pad}.woff2`, `${FONT_BASE}/p${pad}.woff2`),
    ]).then(() => {
      p++;
      localStorage.setItem(WARM_KEY, String(p));
      idle(tick);
    }).catch(() => {
      // Offline / flaky — keep the watermark at this page; a later call resumes.
      warming = false;
    });
  };
  idle(tick);
}


