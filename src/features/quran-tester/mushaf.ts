/**
 * Madani 15-line mushaf — page data + per-page QPC2 glyph fonts, lazy-cached.
 *
 * Source dataset: zonetecde/mushaf-layout (v2 branch, QPC2 edition) — 604
 * pages, each a JSON of typed lines (surah-header / basmala / text) whose
 * words carry `location` ("s:a:w") and `qpcV2` glyph codepoints rendered by
 * that page's own font — the same mechanism quran.com uses.
 *
 * Pages and fonts fetch on first view and cache into the engine bucket, so a
 * page is a one-time ~150KB cost and works offline after.
 */

import { ENGINE_CACHE } from "./engine";

// Page data + fonts proxy through /qt-dl/ — the CSP is self-only for
// connect-src, so cross-origin fetches from the client are blocked.
const BASE = "/qt-dl";
const PAGE_COUNT = 604;

export interface MushafWord {
  location: string; // "surah:ayah:word"
  word: string;
  qpcV2?: string;
}
export interface MushafLine {
  line: number;
  type: "surah-header" | "basmala" | "text" | string;
  text?: string;
  surah?: string;
  verseRange?: string;
  words?: MushafWord[];
  centered?: boolean;
  is_centered?: boolean;
}
export interface MushafPage {
  page: number;
  lines: MushafLine[];
}

/** ayah→page index, generated by scripts/gen-ayah-pages.mjs */
export type AyahPages = Record<string, Record<string, number>>;

export async function loadAyahPages(): Promise<AyahPages> {
  const res = await fetch("/data/ayah-pages.json");
  return res.json();
}

async function cachedAsset(path: string, url: string): Promise<Response> {
  const cache = await caches.open(ENGINE_CACHE);
  const hit = await cache.match(path);
  if (hit) return hit;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`mushaf asset ${path}: ${res.status}`);
  await cache.put(path, res.clone());
  return res;
}

const pageCache = new Map<number, Promise<MushafPage>>();

export function loadPage(n: number): Promise<MushafPage> {
  const p = Math.min(PAGE_COUNT, Math.max(1, n));
  let pending = pageCache.get(p);
  if (!pending) {
    const key = `/qt/page-${String(p).padStart(3, "0")}.json`;
    pending = cachedAsset(key, `${BASE}/page-${String(p).padStart(3, "0")}.json`).then((r) => r.json());
    pageCache.set(p, pending);
  }
  return pending;
}

const loadedFonts = new Set<number>();

/** Register the page's glyph font (downloaded once, cached). */
export async function loadPageFont(n: number): Promise<string> {
  const family = `QPC2-p${n}`;
  if (loadedFonts.has(n)) return family;
  const file = `p${String(n).padStart(3, "0")}.woff2`;
  const res = await cachedAsset(`/qt/${file}`, `${BASE}/${file}`);
  const font = new FontFace(family, await res.arrayBuffer());
  await font.load();
  document.fonts.add(font);
  loadedFonts.add(n);
  return family;
}


